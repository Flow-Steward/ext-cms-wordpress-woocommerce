TEST_CONNECTION_OPERATION_ID = "test_connection"

#: Runs before the connection form saves. The platform's secret-ref validator
#: executes only `required` and `additionalProperties`, so the `dependentRequired`
#: pairing rule and the https-only rule are declared but never enforced at save.
#: This operation enforces them from inside the extension, without reaching the
#: network and without ever receiving a secret value.
VALIDATE_SETTINGS_OPERATION_ID = "validate_connection_settings"
OPERATION_IDS: frozenset[str] = frozenset(REST_OPERATIONS_BY_ID) | {
    TEST_CONNECTION_OPERATION_ID,
    VALIDATE_SETTINGS_OPERATION_ID,
}


def operation(operation_id: Any) -> Operation | None:
    """Return the declared operation, or ``None`` when it is not in the registry."""
    if not isinstance(operation_id, str):
        return None
    return REST_OPERATIONS_BY_ID.get(operation_id.strip())


