"""Closed, statically declared REST operation registry.

Every typed operation this extension can dispatch is declared here as a literal
row. Nothing is derived from ``/wp-json/``, ``OPTIONS``, installed plugins, or
site configuration: an operation that is not in this table cannot be routed, and
a namespace, method, or route that is not carried by a row in this table is
never built into a request. ``contracts/rest_coverage.yaml`` is the published
mirror of this table and is kept in exact parity by the extension-owned tests.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

_PATH_SETTINGS = "/settings"

WORDPRESS = "wordpress"
WOOCOMMERCE = "woocommerce"

WORDPRESS_NAMESPACE = "wp/v2"
WOOCOMMERCE_NAMESPACE = "wc/v3"
SUPPORTED_NAMESPACES: frozenset[str] = frozenset({WORDPRESS_NAMESPACE, WOOCOMMERCE_NAMESPACE})
SUPPORTED_METHODS: frozenset[str] = frozenset({"GET", "POST", "PUT"})

WORDPRESS_DOC_BASE = "https://developer.wordpress.org/rest-api/reference/"
WOOCOMMERCE_DOC_BASE = "https://developer.woocommerce.com/docs/apis/rest-api/v3/"

READ_SHAPES: frozenset[str] = frozenset({"list", "get", "read_post"})
EFFECT_SHAPES: frozenset[str] = frozenset({"create", "update", "batch", "action", "media_create"})
SHAPES: frozenset[str] = READ_SHAPES | EFFECT_SHAPES

PATH_PARAM_KINDS: frozenset[str] = frozenset({"integer", "slug", "namespaced_slug", "plugin_file"})


@dataclass(frozen=True)
class Operation:
    """One typed, statically declared native REST operation."""

    operation_id: str
    provider: str
    resource: str
    namespace: str
    route: str
    method: str
    shape: str
    display_name: str
    doc_slug: str
    path_params: tuple[tuple[str, str], ...] = ()

    @property
    def route_pattern(self) -> str:
        return f"/wp-json/{self.namespace}{self.route}"

    @property
    def doc_url(self) -> str:
        base = WORDPRESS_DOC_BASE if self.provider == WORDPRESS else WOOCOMMERCE_DOC_BASE
        return f"{base}{self.doc_slug}/"

    @property
    def operation_kind(self) -> str:
        return "source" if self.shape in READ_SHAPES else "action"

    @property
    def has_external_effect(self) -> bool:
        return self.shape in EFFECT_SHAPES

    @property
    def category(self) -> str:
        return "cms" if self.provider == WORDPRESS else "ecommerce"

    @property
    def effect_kind(self) -> str:
        return f"{self.provider}_{self.resource}_{self.shape}"

    @property
    def channel(self) -> str:
        return "wordpress_rest" if self.provider == WORDPRESS else "woocommerce_rest"


def _wp(
    operation_id: str,
    resource: str,
    route: str,
    method: str,
    shape: str,
    display_name: str,
    doc_slug: str,
    path_params: tuple[tuple[str, str], ...] = (),
) -> Operation:
    return Operation(
        operation_id=operation_id,
        provider=WORDPRESS,
        resource=resource,
        namespace=WORDPRESS_NAMESPACE,
        route=route,
        method=method,
        shape=shape,
        display_name=display_name,
        doc_slug=doc_slug,
        path_params=path_params,
    )


